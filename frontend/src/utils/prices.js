// PRECIO DE RESPALDO PARA STABLECOINS CUANDO EL BACKEND O LA RED NO ESTAN DISPONIBLES.
// EL BACKEND YA APLICA ESTE FALLBACK; ESTE VALOR ES UNA DEFENSA ADICIONAL EN EL CLIENTE.
export const STABLECOIN_FALLBACK_PRICE = Object.freeze({
    USDT: 1,
    USDC: 1,
});



// DEVUELVE EL PRECIO DE RESPALDO PARA UN SIMBOLO DE STABLECOIN, O 0 SI NO APLICA
export function getStablecoinFallbackPrice(symbol) {
    return STABLECOIN_FALLBACK_PRICE[String(symbol || '').toUpperCase()] || 0;
}
